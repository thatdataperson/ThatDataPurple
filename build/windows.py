"""Windows: a Windows Terminal colour scheme and a Windows 11 theme pack.

Windows Terminal reads the scheme from a settings fragment (one JSON file dropped into its Fragments folder),
so it installs without touching the user's settings.json. The tab row theme can't go in a fragment, so it is
written separately for pasting into settings.json.

Windows itself has no palette-level theme format, so the .deskthemepack only sets what a .theme file can:
the brand wallpaper, the brand purple accent and Dark mode for both Windows and apps. It follows the layout
of Windows 11's own dark.theme. The pack is a CAB with the .theme at its root and the wallpaper in
DesktopBackground\\, built with makecab (Windows only; skipped elsewhere).
"""
import json
import os
import shutil
import subprocess
import tempfile

from colour import from_hls, hls, lighten_until

NAME = 'ThatDataPurple'
WALLPAPER = NAME + '.jpg'
FIXED_TIME = 1767225600  # 2026-01-01: fixed file times so the pack is repeatable


def _brighter(hex_, by=0.08):
    h, l, s = hls(hex_)
    return from_hls(h, l + by, s)


def terminal_scheme(p):
    s, t, x, st = p['surface'], p['text'], p['syntax'], p['status']
    bg, sel = s['ink1'], s['selection']
    base = {
        'red': st['error'], 'green': st['success'], 'yellow': st['warning'], 'blue': x['function'],
        'purple': x['keyword'], 'cyan': x['escape'], 'white': x['operator'],
    }
    # Every colour that is drawn as text has to read on the background and on the selection.
    fit = lambda c: lighten_until(c, [bg, sel], 4.5)  # noqa: E731
    scheme = {'name': NAME, 'background': bg, 'foreground': t['fg'], 'cursorColor': t['link'],
              'selectionBackground': sel, 'black': s['ink3']}
    for k, v in base.items():
        scheme[k] = fit(v)
    scheme['brightBlack'] = fit(t['lineNumber'])
    for k, v in base.items():
        scheme['bright' + k.capitalize()] = fit(_brighter(v))
    scheme['brightWhite'] = t['bright']
    order = ['name', 'background', 'foreground', 'cursorColor', 'selectionBackground', 'black', 'red', 'green',
             'yellow', 'blue', 'purple', 'cyan', 'white', 'brightBlack', 'brightRed', 'brightGreen', 'brightYellow',
             'brightBlue', 'brightPurple', 'brightCyan', 'brightWhite']
    return {k: scheme[k] for k in order}


def terminal_theme(p):
    """Tab row colours. Terminal picks tab text colour itself from the background's lightness."""
    s = p['surface']
    return {
        'name': NAME,
        'window': {'applicationTheme': 'dark', 'useMica': False},
        'tabRow': {'background': s['ink0'] + 'FF', 'unfocusedBackground': s['ink0'] + 'FF'},
        'tab': {'background': 'terminalBackground', 'unfocusedBackground': s['ink0'] + 'FF',
                'showCloseButton': 'always'},
    }


def checks(p):
    sc = terminal_scheme(p)
    bg, sel = sc['background'], sc['selectionBackground']
    text = ['foreground', 'red', 'green', 'yellow', 'blue', 'purple', 'cyan', 'white', 'brightBlack', 'brightRed',
            'brightGreen', 'brightYellow', 'brightBlue', 'brightPurple', 'brightCyan', 'brightWhite']
    out = []
    for k in text:
        out.append((f'Terminal {k} on background', sc[k], bg, 4.5))
        out.append((f'Terminal {k} on selection', sc[k], sel, 4.5))
    # ANSI black is mostly used as a background (status lines, prompts) or as text on white.
    out += [('Terminal foreground on black', sc['foreground'], sc['black'], 4.5),
            ('Terminal white on black', sc['white'], sc['black'], 4.5),
            ('Terminal black on white', sc['black'], sc['white'], 4.5),
            ('Terminal cursor on background', sc['cursorColor'], bg, 3)]
    return out


