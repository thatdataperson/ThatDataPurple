"""Builds every ThatDataPurple theme from palette/palette.json and checks contrast.

The theme repos are expected to be cloned next to this one:

    ThatDataPurple/            (this repo: palette + build)
    ThatDataPurple.VSCode/
    ThatDataPurple.VS2019/
    ThatDataPurple.VS2022/
    ThatDataPurple.Chrome/
    ThatDataPurple.Firefox/   (Firefox, plus Thunderbird in thunderbird/)

Run from anywhere:  python build/build.py  [path-to-folder-holding-the-repos]

Repos that are not cloned are skipped. The build fails (exit 1) if any checked pair falls below its
WCAG target, and writes palette/CONTRAST.md either way.
"""
import json
import os
import re
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import browsers  # noqa: E402
import visualstudio  # noqa: E402
import vs2026  # noqa: E402
import vscode  # noqa: E402
from colour import contrast  # noqa: E402

ROOT = os.path.dirname(HERE)


def main():
    parent = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(ROOT)
    with open(os.path.join(ROOT, 'palette', 'palette.json'), encoding='utf-8') as f:
        palette = json.load(f)

    checks = []

    vsc = os.path.join(parent, 'ThatDataPurple.VSCode', 'themes', 'ThatDataPurple-color-theme.json')
    if os.path.exists(os.path.dirname(vsc)):
        theme, c = vscode.build(palette)
        vscode.write(theme, vsc)
        checks += c
        print('wrote', vsc)

    for version in ('VS2019', 'VS2022'):
        path = os.path.join(parent, f'ThatDataPurple.{version}', f'ThatDataPurple.{version}', 'CustomTheme.vstheme')
        if not os.path.exists(path):
            continue
        # Always start from the original export, so rebuilding is repeatable.
        with open(os.path.join(HERE, 'templates', f'{version}.vstheme'), encoding='utf-8-sig') as f:
            xml = f.read()
        r = visualstudio.Recolourer(palette)
        out = r.recolour(xml, version)
        # Anything the theme doesn't define falls back to VS's Dark theme rather than to nothing.
        out = re.sub(r'(<Theme Name="[^"]+" GUID="\{[^}]+\}")(>)', r'\1 FallbackId="%s"\2' % vs2026.DARK_FALLBACK, out, count=1)
        if version == 'VS2022':
            # The VS2022 extension also installs on VS 2026; add the colours its redesigned UI reads.
            cats = vs2026.categories(palette)
            out = out.replace('\t</Theme>', vs2026.xml(cats) + '\t</Theme>', 1)
            checks += vs2026.checks(cats, version)
        with open(path, 'w', encoding='utf-8-sig', newline='') as f:
            f.write(out)
        checks += r.checks
        print('wrote', path)

    checks += build_browsers(palette, parent)

    failures = [(n, fg, bg, need, contrast(fg, bg)) for n, fg, bg, need in checks if contrast(fg, bg) < need]
    write_report(palette, checks, failures)
    print(f'{len(checks)} contrast checks, {len(failures)} below target')
    for n, fg, bg, need, got in failures:
        print(f'  FAIL {n}: {fg} on {bg} = {got:.2f} (needs {need})')
    return 1 if failures else 0


def build_browsers(palette, parent):
    # (repo, folder holding manifest.json, manifest, tab-indented, package to write)
    targets = [
        ('ThatDataPurple.Chrome', 'chrome-theme', browsers.chrome(palette), True, 'ThatDataPurple.Chrome.zip'),
        ('ThatDataPurple.Firefox', '', browsers.firefox(palette), False, 'ThatDataPurple.Firefox.xpi'),
        ('ThatDataPurple.Firefox', 'thunderbird', browsers.thunderbird(palette), False, 'ThatDataPurple.Thunderbird.xpi'),
    ]
    built = False
    for repo, folder, manifest, tabs, package in targets:
        root = os.path.join(parent, repo)
        if not os.path.exists(root):
            continue
        built = True
        src = os.path.join(root, folder)
        os.makedirs(os.path.join(src, 'images'), exist_ok=True)
        browsers.write(manifest, os.path.join(src, 'manifest.json'), tabs)
        icon = manifest['icons']['128']
        with open(os.path.join(HERE, 'templates', 'icon128.png'), 'rb') as f, open(os.path.join(src, icon), 'wb') as g:
            g.write(f.read())
        os.makedirs(os.path.join(root, 'bin', 'Release'), exist_ok=True)
        with zipfile.ZipFile(os.path.join(root, 'bin', 'Release', package), 'w', zipfile.ZIP_DEFLATED) as z:
            for name in ('manifest.json', icon):
                info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))  # fixed date: repeatable builds
                info.compress_type = zipfile.ZIP_DEFLATED
                with open(os.path.join(src, name), 'rb') as f:
                    z.writestr(info, f.read())
        print('wrote', os.path.join(src, 'manifest.json'), '+', package)
    return browsers.checks(palette) if built else []


def write_report(p, checks, failures):
    s, t, x = p['surface'], p['text'], p['syntax']
    lines = [
        '# Contrast report',
        '',
        'Generated by `build/build.py`. Ratios are WCAG 2.2 contrast ratios. Text needs 4.5:1 (AA),',
        'focus indicators and icons need 3:1.',
        '',
        '## Syntax colours',
        '',
        '| Role | Colour | Editor `%s` | Current line `%s` | Selection `%s` |' % (s['ink1'], s['ink2'], s['selection']),
        '|---|---|---|---|---|',
    ]
    for role, fg in [('Plain text', t['fg'])] + list(x.items()) + [('Line numbers', t['lineNumber']), ('Links', t['link'])]:
        lines.append('| %s | `%s` | %.1f | %.1f | %.1f |' % (role, fg, contrast(fg, s['ink1']), contrast(fg, s['ink2']), contrast(fg, s['selection'])))
    worst = min(checks, key=lambda c: contrast(c[1], c[2]) / c[3]) if checks else None
    lines += [
        '',
        '## Totals',
        '',
        f'- Pairs checked: {len(checks)}',
        f'- Below target: {len(failures)}',
    ]
    if worst:
        lines.append(f'- Closest to the line: {worst[0]}, `{worst[1]}` on `{worst[2]}` at {contrast(worst[1], worst[2]):.2f}:1 (target {worst[3]})')
    for n, fg, bg, need, got in failures:
        lines.append(f'- FAIL {n}: `{fg}` on `{bg}` = {got:.2f}')
    with open(os.path.join(ROOT, 'palette', 'CONTRAST.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    sys.exit(main())
