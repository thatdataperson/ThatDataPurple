def wallpaper(p, out, size=3840, height=None):
    """A diagonal shift from brand dark (top left) to brand purple (bottom right), with no logo or text.

    Square by default, so 'fill' crops it sensibly on landscape and portrait screens alike. Pass a height
    for a screen-sized version (the phone wallpapers)."""
    import numpy as np
    from PIL import Image

    from colour import rgb

    height = height or size
    yy, xx = np.mgrid[0:height, 0:size].astype(np.float32)
    yy, xx = yy / (height - 1), xx / (size - 1)
    t = np.clip((xx + yy) / 2, 0, 1)
    t = t * t * (3 - 2 * t)  # smoothstep: longer dark and purple ends, soft middle
    dark, purple = (np.array(rgb(p['brand'][k]), np.float32) for k in ('dark', 'purple'))
    img = dark + (purple - dark) * t[..., None]
    # A faint lift of light purple towards the bottom-right corner keeps the purple end from looking flat.
    d = np.sqrt((1 - xx) ** 2 + (1 - yy) ** 2) / 0.9
    a = (np.clip(1 - d, 0, 1) ** 2 * 0.18)[..., None]
    img = img * (1 - a) + np.array(rgb(p['brand']['lightPurple']), np.float32) * a
    # A little fixed noise stops the gradient banding in the JPEG.
    img += np.random.default_rng(2026).normal(0, 1.1, img.shape).astype(np.float32)
    Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), 'RGB').save(out, quality=92, subsampling=0, optimize=True)


def build(p, out_root):
    """Writes windows/terminal and windows/theme under out_root, plus the .deskthemepack. Returns paths written."""
    written = []
    term = os.path.join(out_root, 'terminal')
    os.makedirs(term, exist_ok=True)
    fragment = {
        '$help': 'https://aka.ms/terminal-documentation',
        '$comment': 'ThatDataPurple colour scheme by That Data Person Limited. Generated by build/build.py.',
        'schemes': [terminal_scheme(p)],
    }
    for name, data in ((f'{NAME}.json', fragment), ('theme.json', terminal_theme(p))):
        path = os.path.join(term, name)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            json.dump(data, f, indent=4)
            f.write('\n')
        written.append(path)

    theme = os.path.join(out_root, 'theme')
    bgdir = os.path.join(theme, 'DesktopBackground')
    os.makedirs(bgdir, exist_ok=True)
    theme_path = os.path.join(theme, f'{NAME}.theme')
    with open(theme_path, 'w', encoding='utf-8-sig', newline='') as f:
        f.write(theme_file(p))
    jpg = os.path.join(bgdir, WALLPAPER)
    wallpaper(p, jpg)
    written += [theme_path, jpg]

    pack = os.path.join(out_root, 'bin', 'Release', f'{NAME}.deskthemepack')
    if shutil.which('makecab'):
        os.makedirs(os.path.dirname(pack), exist_ok=True)
        _cab(pack, [(theme_path, ''), (jpg, 'DesktopBackground')])
        written.append(pack)
    return written


def _cab(out, files):
    for f, _ in files:
        os.utime(f, (FIXED_TIME, FIXED_TIME))
    with tempfile.TemporaryDirectory() as tmp:
        ddf = os.path.join(tmp, 'pack.ddf')
        lines = ['.Set CabinetNameTemplate=' + os.path.basename(out), '.Set DiskDirectoryTemplate=' + tmp,
                 '.Set Cabinet=on', '.Set Compress=on', '.Set CompressionType=MSZIP', '.Set MaxDiskSize=0',
                 '.Set RptFileName=NUL', '.Set InfFileName=NUL']
        for f, dest in files:
            lines += ['.Set DestinationDir=' + dest, f'"{f}"']
        with open(ddf, 'w', encoding='ascii') as fh:
            fh.write('\r\n'.join(lines) + '\r\n')
        subprocess.run(['makecab', '/F', ddf], check=True, capture_output=True, cwd=tmp)
        shutil.copyfile(os.path.join(tmp, os.path.basename(out)), out)
