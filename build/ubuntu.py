"""Ubuntu (GNOME): a Ptyxis terminal palette, libadwaita colours for GNOME apps, and the brand wallpaper.

Ptyxis (Ubuntu's terminal since 25.10) reads palettes from ~/.local/share/org.gnome.Ptyxis/palettes, one key file
per palette with [Light] and [Dark] groups. ThatDataPurple is dark only, so both groups carry the same colours.
The ANSI colours are the Windows Terminal scheme's, so the two terminals match.

GNOME apps built on libadwaita read ~/.config/gtk-4.0/gtk.css after their theme, so the CSS variables set there
recolour windows, sidebars, header bars, cards, popovers and the accent. GTK 3 apps and the GNOME Shell top bar
can't be recoloured that way; install.sh sets GNOME's own purple accent and dark style for those.
"""
import os
import shutil

import windows
from colour import lighten_until

NAME = 'ThatDataPurple'
WALLPAPER = NAME + '.jpg'


def gtk_colours(p):
    s, t, st = p['surface'], p['text'], p['status']
    fit = lambda c: lighten_until(c, [s['ink1'], s['ink2'], s['ink3']], 4.5)  # noqa: E731
    # Ordered as in the libadwaita CSS variables documentation.
    return {
        'accent-color': fit(t['accent']),
        'accent-bg-color': s['primary'],
        'accent-fg-color': t['bright'],
        'destructive-color': fit(st['error']),
        'destructive-bg-color': '#B3263A',
        'destructive-fg-color': t['bright'],
        'success-color': fit(st['success']),
        'warning-color': fit(st['warning']),
        'error-color': fit(st['error']),
        'window-bg-color': s['ink1'],
        'window-fg-color': t['fg'],
        'view-bg-color': s['ink1'],
        'view-fg-color': t['fg'],
        'headerbar-bg-color': s['ink0'],
        'headerbar-fg-color': t['fg'],
        'headerbar-border-color': s['border'],
        'headerbar-backdrop-color': s['ink0'],
        'headerbar-shade-color': 'rgb(0 0 0 / 36%)',
        'sidebar-bg-color': s['ink0'],
        'sidebar-fg-color': t['fg'],
        'sidebar-backdrop-color': s['ink0'],
        'sidebar-border-color': s['border'],
        'sidebar-shade-color': 'rgb(0 0 0 / 36%)',
        'secondary-sidebar-bg-color': s['ink0'],
        'secondary-sidebar-fg-color': t['fg'],
        'secondary-sidebar-backdrop-color': s['ink0'],
        'secondary-sidebar-border-color': s['border'],
        'card-bg-color': s['ink2'],
        'card-fg-color': t['fg'],
        'card-shade-color': 'rgb(0 0 0 / 36%)',
        'dialog-bg-color': s['ink2'],
        'dialog-fg-color': t['fg'],
        'popover-bg-color': s['ink3'],
        'popover-fg-color': t['fg'],
        'popover-shade-color': 'rgb(0 0 0 / 25%)',
        'thumbnail-bg-color': s['ink2'],
        'thumbnail-fg-color': t['fg'],
        'shade-color': 'rgb(0 0 0 / 36%)',
        'scrollbar-outline-color': 'rgb(0 0 0 / 50%)',
    }


def gtk_css(p):
    lines = [
        '/* ThatDataPurple for GNOME apps (libadwaita), by That Data Person Limited (www.thatdataperson.com).',
        ' * Generated by build/build.py in github.com/thatdataperson/ThatDataPurple. */',
        '',
        ':root {',
    ]
    lines += [f'  --{k}: {v};' for k, v in gtk_colours(p).items()]
    return '\n'.join(lines + ['}', ''])


def palette_file(p):
    sc = windows.terminal_scheme(p)
    s, t = p['surface'], p['text']
    ansi = ['black', 'red', 'green', 'yellow', 'blue', 'purple', 'cyan', 'white']
    face = [f'Foreground={sc["foreground"]}', f'Background={sc["background"]}',
            f'CursorBackground={sc["cursorColor"]}', f'CursorForeground={sc["background"]}']
    face += [f'Color{i}={sc[k]}' for i, k in enumerate(ansi)]
    face += [f'Color{i + 8}={sc["bright" + k.capitalize()]}' for i, k in enumerate(ansi)]
    face += ['',
             f'TitlebarBackground={s["ink0"]}', f'TitlebarForeground={t["fg"]}',
             f'BellBackground={s["ink3"]}', f'BellForeground={t["bright"]}',
             f'SuperuserBackground={s["primary"]}', f'SuperuserForeground={t["bright"]}',
             f'RemoteBackground={s["selection"]}', f'RemoteForeground={t["bright"]}']
    head = ['# ThatDataPurple for Ptyxis, by That Data Person Limited (www.thatdataperson.com).',
            '# Generated by build/build.py in github.com/thatdataperson/ThatDataPurple.',
            '', '[Palette]', f'Name={NAME}', '']
    return '\n'.join(head + ['[Light]'] + face + ['', '[Dark]'] + face) + '\n'


def checks(p):
    c = gtk_colours(p)
    s, t = p['surface'], p['text']
    out = []
    for fg, bg in [('window-fg-color', 'window-bg-color'), ('headerbar-fg-color', 'headerbar-bg-color'),
                   ('sidebar-fg-color', 'sidebar-bg-color'), ('card-fg-color', 'card-bg-color'),
                   ('dialog-fg-color', 'dialog-bg-color'), ('popover-fg-color', 'popover-bg-color'),
                   ('accent-fg-color', 'accent-bg-color'), ('destructive-fg-color', 'destructive-bg-color')]:
        out.append((f'GNOME {fg} on {bg}', c[fg], c[bg], 4.5))
    for fg in ('accent-color', 'destructive-color', 'success-color', 'warning-color', 'error-color'):
        for bg in ('window-bg-color', 'card-bg-color', 'popover-bg-color'):
            out.append((f'GNOME {fg} on {bg}', c[fg], c[bg], 4.5))
    out += [('Ptyxis title bar text', t['fg'], s['ink0'], 4.5),
            ('Ptyxis superuser title bar text', t['bright'], s['primary'], 4.5),
            ('Ptyxis remote title bar text', t['bright'], s['selection'], 4.5)]
    return out


def build(p, out_root, wallpaper_src):
    """Writes ubuntu/terminal, ubuntu/gtk-4.0 and ubuntu/backgrounds under out_root. Returns paths written.

    The wallpaper is the one built for Windows, copied so this folder installs on its own."""
    written = []
    for folder, name, text in (('terminal', f'{NAME}.palette', palette_file(p)), ('gtk-4.0', 'gtk.css', gtk_css(p))):
        os.makedirs(os.path.join(out_root, folder), exist_ok=True)
        path = os.path.join(out_root, folder, name)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        written.append(path)
    bg = os.path.join(out_root, 'backgrounds', WALLPAPER)
    os.makedirs(os.path.dirname(bg), exist_ok=True)
    shutil.copyfile(wallpaper_src, bg)
    written.append(bg)
    return written
